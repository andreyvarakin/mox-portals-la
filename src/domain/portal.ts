/**
 * Статус портала.
 *
 * - OPEN — портал открыт.
 * - QUESTIONABLE — портал физически открыт, но оператор пометил его
 *   как требующий внимания. Это не уровень риска: риск вычисляется
 *   отдельно из параметров портала (см. RiskResult).
 * - CLOSED — портал закрыт.
 */
export type PortalStatus = 'OPEN' | 'QUESTIONABLE' | 'CLOSED'

/**
 * Портал лаборатории.
 *
 * Хранит только исходные параметры. Риск и рекомендуемое действие
 * не хранятся — они вычисляются из этих полей.
 *
 * Диапазоны и целочисленность типами не выражаются и сейчас не проверяются.
 */
export interface Portal {
  id: string
  name: string
  destinationWorld: string
  /** Уровень энергии, 0–100. */
  energy: number
  /** Стабильность, 0–100. */
  stability: number
  /**
   * Минут до схлопывания для активного портала.
   * null допустим для закрытого портала.
   */
  collapseMinutes: number | null
  /** Существ внутри: неотрицательное целое. */
  creaturesInside: number
  status: PortalStatus
}
